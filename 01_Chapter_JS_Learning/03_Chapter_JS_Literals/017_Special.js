// 5. Special Numeric values

//Infinity
console.log("Infinity:", Infinity);
console.log("1/0:", 1/0);
console.log("-1/0:", -1/0);
console.log("type of Infinity:", typeof Infinity);

console.log("-Infinity" , -Infinity);

//Nan - Not a Number - result of invalid math
console.log("NaN:", NaN);
console.log("0/0:", 0/0);
console.log("'hello' *2:", "hello" * 2);
console.log("typeof Nan:", typeof Nan);